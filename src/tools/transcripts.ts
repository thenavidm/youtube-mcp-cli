/**
 * Transcript tools.
 *
 * These are the only tools that work with no credentials of any kind, and they
 * read anyone's video rather than only your own. For most people this is the
 * reason to install the server at all, so it is the group listed first.
 */

import { z } from "zod";
import {
  fetchTranscript,
  formatTimestamp,
  listTracks,
  parseVideoId,
  searchSegments,
  toPlainText,
  toTimestampedText,
} from "../youtube/transcripts.js";
import { fetchMostReplayed, YtDlpMissingError, type MostReplayed } from "../youtube/ytdlp.js";
import { defineTool, type AnyToolSpec } from "./kit.js";
import { NotConfiguredError, UsageError } from "@thenavidm/slipway";

/** Local peaks after the opening: the opening is nearly always the top, since every view starts there. */
export function replayPeaks(m: MostReplayed, top = 5): { start: number; end: number; value: number }[] {
  const pts = m.points;
  const skip = Math.ceil(pts.length * 0.05);
  const peaks = pts.filter((p, i) => i >= skip && p.value >= (pts[i - 1]?.value ?? 0) && p.value >= (pts[i + 1]?.value ?? 0));
  return peaks.sort((a, b) => b.value - a.value).slice(0, top);
}

const clock = (s: number) => formatTimestamp(Math.floor(s));

const video = z
  .string()
  .describe("Video id or any YouTube URL: watch, youtu.be, Shorts, embed or live.");

export const transcriptTools: AnyToolSpec[] = [
  defineTool({
    name: "get_transcript",
    title: "Get transcript",
    description:
      "Read the transcript of ANY public YouTube video, not just your own. Needs no API key, no connected account and no quota. Returns prose by default, or timestamped lines when you need to cite a moment. Videos with captions disabled have no transcript and nothing can recover one.",
    schema: {
      video,
      language: z
        .string()
        .optional()
        .describe("Language code such as `en`, `es`, `de`. Defaults to English, then whatever exists."),
      timestamps: z
        .boolean()
        .optional()
        .describe("Return `[m:ss] text` lines instead of prose. Use when you need to point at a moment."),
      group_seconds: z
        .number()
        .min(5)
        .max(300)
        .optional()
        .describe("Seconds of speech per timestamped line. Default 30."),
    },
    risk: "read",
    handler: async ({ video: v, language, timestamps, group_seconds }, ctx) => {
      const t = await fetchTranscript(v, { language: language ?? ctx.config.defaultLanguage });
      const body = timestamps
        ? toTimestampedText(t.segments, group_seconds ?? 30)
        : toPlainText(t.segments);
      return (
        `video: ${t.videoId}\nlanguage: ${t.language}${t.autoGenerated ? " (auto-generated)" : ""}\n` +
        `segments: ${t.segments.length}\n\n${body}`
      );
    },
  }),

  defineTool({
    name: "list_transcript_languages",
    title: "List transcript languages",
    description:
      "List every caption language on a video and whether each was written by a human or auto-generated. Human captions are more accurate. Call this before get_transcript when the video may not be in English.",
    schema: { video },
    risk: "read",
    handler: async ({ video: v }) => {
      const id = parseVideoId(v);
      if (!id) throw new UsageError(`Could not read a video id out of "${v}".`);
      const tracks = await listTracks(id);
      if (tracks.length === 0) return "This video has no captions.";
      return tracks
        .map((t) => `${t.languageCode}\t${t.languageName}${t.autoGenerated ? "\t(auto-generated)" : ""}`)
        .join("\n");
    },
  }),

  defineTool({
    name: "search_transcript",
    title: "Search inside a video",
    description:
      "Find every place a phrase is said in a video and get the timestamps, each as a link that jumps to that second. Use this instead of pulling a whole transcript when you only need to locate something.",
    schema: {
      video,
      query: z.string().min(1).describe("The phrase to find. Case-insensitive substring match."),
      language: z.string().optional(),
      context_segments: z
        .number()
        .min(0)
        .max(5)
        .optional()
        .describe("Caption segments either side to include for context. Default 1."),
    },
    risk: "read",
    handler: async ({ video: v, query, language, context_segments }, ctx) => {
      const t = await fetchTranscript(v, { language: language ?? ctx.config.defaultLanguage });
      const hits = searchSegments(t.segments, query, context_segments ?? 1);
      if (hits.length === 0) return `"${query}" is not said in this video.`;
      const body = hits
        .map((h) => `[${h.timestamp}] https://youtu.be/${t.videoId}?t=${Math.floor(h.start)}\n${h.text}`)
        .join("\n\n");
      return `${hits.length} match(es)\n\n${body}`;
    },
  }),

  defineTool({
    name: "get_transcripts",
    title: "Get several transcripts",
    description:
      "Fetch transcripts for up to 20 videos in one call. A video with no captions is reported in place rather than failing the batch. Use it to compare how a set of videos open, or to build a corpus before analyzing it.",
    schema: {
      videos: z.array(video).min(1).max(20).describe("Up to 20 video ids or URLs."),
      language: z.string().optional(),
      max_chars_each: z
        .number()
        .min(200)
        .optional()
        .describe("Truncate each transcript to this many characters. Useful when you only need the openings."),
    },
    risk: "read",
    handler: async ({ videos, language, max_chars_each }, ctx) => {
      const parts: string[] = [];
      for (const v of videos) {
        try {
          const t = await fetchTranscript(v, { language: language ?? ctx.config.defaultLanguage });
          let text = toPlainText(t.segments);
          if (max_chars_each && text.length > max_chars_each) text = `${text.slice(0, max_chars_each)}…`;
          parts.push(`### ${t.videoId} (${t.language})\n${text}`);
        } catch (err) {
          parts.push(`### ${v}\nNo transcript: ${err instanceof Error ? err.message : String(err)}`);
        }
      }
      return parts.join("\n\n");
    },
  }),
  defineTool({
    name: "get_most_replayed",
    title: "Get most replayed moments",
    description:
      "Read YouTube's public Most replayed graph for ANY video: about 100 stretches, each scored against the most replayed one, which is 1. It is the only public trace of where viewers rewatch, so use it on other creators' videos where analytics are not yours to read. Needs no API key or account, only yt-dlp. YouTube shows the graph only once a video has enough views; below that there is nothing to read.",
    schema: {
      video,
      format: z
        .enum(["text", "tsv"])
        .optional()
        .describe("text (default): the opening and the top peaks after it. tsv: every stretch as start, end, value."),
    },
    risk: "read",
    handler: async ({ video: v, format }) => {
      const id = parseVideoId(v);
      if (!id) throw new UsageError(`Could not read a video id out of "${v}".`);
      let m: MostReplayed;
      try {
        m = await fetchMostReplayed(id);
      } catch (err) {
        if (err instanceof YtDlpMissingError) throw new NotConfiguredError(err.message);
        throw err;
      }
      if (m.points.length === 0)
        return `video: ${id}\nYouTube shows no Most replayed graph for this video. It appears only once a video has enough views.`;
      if (format === "tsv") return ["start\tend\tvalue", ...m.points.map((p) => `${p.start}\t${p.end}\t${p.value.toFixed(4)}`)].join("\n");
      const step = m.points[0]!.end - m.points[0]!.start;
      const lines = replayPeaks(m).map(
        (p) => `[${clock(p.start)}-${clock(p.end)}] ${p.value.toFixed(2)}  https://youtu.be/${id}?t=${Math.floor(p.start)}`,
      );
      return [
        `video: ${id}`,
        m.title,
        `${m.points.length} stretches of about ${step.toFixed(1)} seconds; 1.00 is the most replayed.`,
        `opening [${clock(m.points[0]!.start)}-${clock(m.points[0]!.end)}]: ${m.points[0]!.value.toFixed(2)}`,
        "",
        "Peaks after the opening:",
        ...(lines.length ? lines : ["none"]),
      ].join("\n");
    },
  }),
].map((t) => t as AnyToolSpec);
